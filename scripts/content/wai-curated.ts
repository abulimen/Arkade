// Validate and clean curated bank into WaiRows (skipping anything in seedNames)
export function sanitizeCuratedAnswerLeaks(
  row: CuratedWaiSeed,
  verseByRef: Map<string, { ref: string; text: string }>
): WaiRow | null {
  if (!verseByRef.has(row.ref.toLowerCase())) {
    throw new Error(`[CURATED_WAI_BANK] Invalid ref "${row.ref}" for "${row.name}"`);
  }

  const nameLower = row.name.toLowerCase();
  const forbiddenParts = new Set<string>([
    nameLower,
    ...row.name
      .toLowerCase()
      .split(/[\s,'’]+/)
      .filter((w) => w.length >= 4 && !['with', 'that', 'from', 'into'].includes(w)),
    ...(row.aliases ?? []).map((a) => a.toLowerCase()),
  ]);

  for (let i = 0; i < 5; i++) {
    const clue = row.clues[i];
    if (!clue || clue.length < 15) {
      throw new Error(`[CURATED_WAI_BANK] Clue ${i + 1} too short for "${row.name}"`);
    }
    const cl = clue.toLowerCase();
    for (const part of forbiddenParts) {
      const re = new RegExp(`\\b${part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`, 'i');
      if (re.test(cl)) {
        throw new Error(
          `[CURATED_WAI_BANK] Clue ${i + 1} for "${row.name}" leaks forbidden token "${part}": "${clue}"`
        );
      }
    }
  }

  if (row.distractors.length !== 5 || new Set([row.name, ...row.distractors]).size !== 6) {
    throw new Error(`[CURATED_WAI_BANK] Invalid distractors for "${row.name}"`);
  }

  const aud = row.d === 'e' ? 'kya' : 'ya';
  const id = `cur-wai-${row.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`;
  return [
    id,
    row.d,
    aud,
    row.testament,
    row.ref,
    row.name,
    [...row.clues],
    [...row.distractors],
    row.story,
  ];
}
